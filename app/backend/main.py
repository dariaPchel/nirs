from rag.bm25 import build_index
from rag.rag import run_rag, continue_rag


def main():

    # Строим индекс BM25
    bm25_index = build_index(docs)

    print("Индекс BM25 построен!")
    print(f"Количество документов: {bm25_index['N']}")
    print(f"Средняя длина документа: {bm25_index['avgdl']:.2f}")
    print()

    # Получаем сообщение пользователя
    question = input("Напишите сообщение: ")

    # Первый этап: поиск и расследование
    state = run_rag(
        question=question,
        docs=docs,
        bm25_index=bm25_index,
        k=3
    )

    # Показываем найденные документы
    print("\nНайденные документы:")

    for source in state["sources"]:
        print(
            f"\n{source['id']} — {source['schema']}"
            f"\nОценка BM25: {source['score']:.4f}"
        )

    # Показываем результат расследования
    print("\nFRAUDI:")
    print(state["description"])

    # Если подходящая схема найдена — спрашиваем разрешение
    if state["status"] == "awaiting_confirmation":

        answer = input(
            "\nРассказать, что делать с этим дальше? (да/нет): "
        )

        if answer.strip().lower() in ("да", "д", "yes"):

            # Второй этап: получение рекомендаций
            state = continue_rag(state, docs)

            print("\nРекомендации FRAUDI:")
            print(state["answer"])

        else:
            print(
                "\nХорошо. Если появятся новые обстоятельства, "
                "мы сможем продолжить расследование."
            )

    else:
        print(
            "\nПодходящая схема не определена. "
            "Дополнительные рекомендации пока недоступны."
        )


if __name__ == "__main__":
    main()
