def main():

    # Строим индекс BM25
    bm25_index = build_index(docs)

    print("Индекс BM25 построен!")
    print(f"Количество документов: {bm25_index['N']}")
    print(f"Средняя длина документа: {bm25_index['avgdl']:.2f}")
    print()

    # Вводим запрос пользователя
    question = input("Напишите сообщение: ")

    # Запускаем RAG
    result = run_rag(
        question=question,
        docs=docs,
        bm25_index=bm25_index,
        k=5
    )

    # Выводим найденные документы
    print("\nНайденные документы:")

    if not result["sources"]:
        print("Документы не найдены.")

    for source in result["sources"]:
        print(
            f"\n{source['id']} — {source['schema']}"
            f"\nОценка BM25: {source['score']:.4f}"
        )

    # Выводим ответ языковой модели
    print("\nОтвет FRAUDI:")
    print(result["answer"])

    # Выводим источники ответа
    print("\nИсточники:")
    for source in result["sources"]:
        print(f"- {source['id']}: {source['schema']}")


if __name__ == "__main__":
    main()
